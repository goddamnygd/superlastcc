-- Schema for the Dead by Daylight Character Directory API.
-- Run this first in the Supabase SQL Editor, then run seed.sql.

create table if not exists public.characters (
  id              bigint generated by default as identity primary key,
  name            text not null check (length(trim(name)) > 0),
  character_code  text not null unique check (length(trim(character_code)) > 0),
  role            text not null check (role in ('Survivor', 'Killer')),
  gender          text not null,
  origin          text not null,
  realm           text not null,
  dlc             text not null,
  year            integer not null check (year between 2016 and 2100),
  perk_1          text not null,
  perk_2          text not null,
  perk_3          text not null,
  difficulty      text not null check (difficulty in ('Easy', 'Intermediate', 'Hard', 'Very Hard')),
  power           text not null default 'None',
  description     text not null,
  image           text,
  movement_speed  text not null,
  terror_radius   text not null,
  height          text not null default 'N/A',
  voice_actor     text not null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- Indexes for the filters and sorting the API uses
create index if not exists characters_role_idx on public.characters (role);
create index if not exists characters_name_idx on public.characters (name);
create index if not exists characters_year_idx on public.characters (year);

-- Keep updated_at fresh on every update
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists characters_set_updated_at on public.characters;
create trigger characters_set_updated_at
before update on public.characters
for each row execute function public.set_updated_at();

-- Lock the table down. RLS on with no policies means the public anon key cannot read
-- or write anything. Only the API, using the server-side service_role key, can.
alter table public.characters enable row level security;
