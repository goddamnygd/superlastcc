-- Perks and powers in the database.
-- Run AFTER schema.sql and seed.sql (it reads the perk and power names already in `characters`).
-- Safe to run again: every insert is "on conflict do nothing / do update".
--
-- What lives here:
--   perk_kinds   the simple one-use moves a perk can be (per side: survivor / killer) and their help text
--   perks        every perk name, which side it belongs to, and which move it turns into
--   power_kinds  the Killer power mechanics: cooldown (turns), attack boost and help text
--   powers       every Killer power name and which mechanic it uses
-- The API reads these tables for the Trial games (api/_catalog.py). The Python lists are only a
-- fallback if the tables are empty or unreachable. To change what a perk or power does, update a
-- row (or call PATCH /api/v1/perks/{id}) instead of editing code and redeploying.
-- The `characters` table still stores the names as text, so existing endpoints do not change.

create table if not exists public.perk_kinds (
  side          text not null check (side in ('survivor', 'killer')),
  kind          text not null check (length(trim(kind)) > 0),
  help          text not null,
  default_slot  smallint check (default_slot between 1 and 3),   -- kind a NEW perk gets in this slot (1-3)
  primary key (side, kind)
);
create unique index if not exists perk_kinds_default_slot_uidx on public.perk_kinds (side, default_slot) where default_slot is not null;

create table if not exists public.perks (
  id          bigint generated by default as identity primary key,
  name        text not null check (length(trim(name)) > 0),
  side        text not null check (side in ('survivor', 'killer')),
  kind        text not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (side, name),
  foreign key (side, kind) references public.perk_kinds (side, kind) on update cascade
);
create index if not exists perks_kind_idx on public.perks (side, kind);

create table if not exists public.power_kinds (
  kind        text primary key check (length(trim(kind)) > 0),
  cooldown    integer not null check (cooldown between 0 and 20),       -- turns before it is ready again
  boost       numeric(4,2) not null default 0 check (boost between 0 and 1),   -- extra hit chance
  help        text not null,
  is_default  boolean not null default false                            -- kind a NEW power gets
);
create unique index if not exists power_kinds_one_default_uidx on public.power_kinds (is_default) where is_default;

create table if not exists public.powers (
  id          bigint generated by default as identity primary key,
  name        text not null unique check (length(trim(name)) > 0),
  kind        text not null references public.power_kinds (kind) on update cascade,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists powers_kind_idx on public.powers (kind);

drop trigger if exists perks_set_updated_at on public.perks;
create trigger perks_set_updated_at before update on public.perks
for each row execute function public.set_updated_at();
drop trigger if exists powers_set_updated_at on public.powers;
create trigger powers_set_updated_at before update on public.powers
for each row execute function public.set_updated_at();

