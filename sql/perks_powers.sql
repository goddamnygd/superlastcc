-- ---------- new characters register their perks and powers automatically ----------
-- Any perk or power name that is not in the tables yet is added with the default kind for its slot
-- (the same fallback the Python code used), so a Killer added by an admin never breaks the games.
create or replace function public.sync_catalog_from_character()
returns trigger language plpgsql as $$
declare
  v_side text := case when new.role = 'Killer' then 'killer' else 'survivor' end;
begin
  insert into public.perks (name, side, kind)
  select p.name, v_side, k.kind
  from (values (new.perk_1, 1), (new.perk_2, 2), (new.perk_3, 3)) as p(name, slot)
  join public.perk_kinds k on k.side = v_side and k.default_slot = p.slot
  where p.name is not null and length(trim(p.name)) > 0
  on conflict (side, name) do nothing;

  if new.role = 'Killer' and new.power is not null and length(trim(new.power)) > 0 and new.power <> 'None' then
    insert into public.powers (name, kind)
    select new.power, k.kind from public.power_kinds k where k.is_default
    on conflict (name) do nothing;
  end if;
  return new;
end;
$$;

drop trigger if exists characters_sync_catalog on public.characters;
create trigger characters_sync_catalog
after insert or update of perk_1, perk_2, perk_3, power, role on public.characters
for each row execute function public.sync_catalog_from_character();

-- Register everything already in `characters` that the lists above did not cover.
insert into public.perks (name, side, kind)
select p.name, case when c.role = 'Killer' then 'killer' else 'survivor' end, k.kind
from public.characters c
cross join lateral (values (c.perk_1, 1), (c.perk_2, 2), (c.perk_3, 3)) as p(name, slot)
join public.perk_kinds k
  on k.side = case when c.role = 'Killer' then 'killer' else 'survivor' end and k.default_slot = p.slot
where length(trim(p.name)) > 0
on conflict (side, name) do nothing;

insert into public.powers (name, kind)
select distinct c.power, k.kind
from public.characters c
join public.power_kinds k on k.is_default
where c.role = 'Killer' and length(trim(c.power)) > 0 and c.power <> 'None'
on conflict (name) do nothing;
