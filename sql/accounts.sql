-- Accounts: roles, users, equipped avatar, audit log and the security functions.
-- Run in the Supabase SQL Editor AFTER schema.sql and seed.sql.
-- If you had an older version of these tables, run reset_accounts.sql first.
--
-- How the tables connect:
--   roles 1 ---- * users             users.role_id -> roles.id
--   users 1 ---- 0..1 characters     through equipped_avatar (user_id is the primary key,
--                                    so one user can only ever equip ONE avatar)
--   users 1 ---- * audit_log         audit_log.user_id -> users.id (kept as NULL if the user is deleted)

-- ============ roles ============
create table if not exists public.roles (
  id           smallint primary key,
  name         text not null unique check (name = lower(name)),
  description  text not null
);

-- Fixed ids: the API relies on 1 = user and 2 = admin
insert into public.roles (id, name, description) values
  (1, 'user',  'Normal account. Manages own profile, equips one avatar and levels it up by winning games.'),
  (2, 'admin', 'Can manage characters and other accounts, and read the audit log.')
on conflict (id) do nothing;

-- ============ users ============
create table if not exists public.users (
  id                     bigint generated by default as identity primary key,
  username               text not null,
  email                  text not null,
  password_hash          text not null,
  role_id                smallint not null default 1
                           references public.roles (id) on update cascade on delete restrict,
  is_active              boolean not null default true,
  token_version          integer not null default 0,   -- raising this invalidates every login token
  failed_login_attempts  integer not null default 0 check (failed_login_attempts >= 0),
  locked_until           timestamptz,
  last_login_at          timestamptz,
  last_win_at            timestamptz,                  -- for the win cooldown
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  constraint users_username_key unique (username),
  constraint users_email_key unique (email),
  constraint users_username_format check (username ~ '^[a-z0-9_]{3,30}$'),
  constraint users_email_lowercase check (email = lower(email))
);

create index if not exists users_role_id_idx on public.users (role_id);

-- Keep updated_at fresh on every update (also created in schema.sql, safe to repeat)
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists users_set_updated_at on public.users;
create trigger users_set_updated_at
before update on public.users
for each row execute function public.set_updated_at();

-- The system must always keep at least one active admin. This is enforced here, in the
-- database, so no API bug or race can lock everyone out. (role id 2 = admin)
create or replace function public.protect_last_admin()
returns trigger language plpgsql set search_path = public as $$
begin
  if old.role_id = 2 and old.is_active then
    if tg_op = 'DELETE' or new.role_id <> 2 or not new.is_active then
      if not exists (
        select 1 from public.users where role_id = 2 and is_active and id <> old.id
      ) then
        raise exception 'last_admin: at least one active admin must remain' using errcode = 'P0001';
      end if;
    end if;
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists users_protect_last_admin on public.users;
create trigger users_protect_last_admin
before update or delete on public.users
for each row execute function public.protect_last_admin();

-- ============ equipped avatar ============
-- user_id is the PRIMARY KEY, so the database itself guarantees one avatar per user.
-- It only records WHICH character is equipped; XP, level, wins and Prestige live per character in avatar_progress.
create table if not exists public.equipped_avatar (
  user_id       bigint primary key references public.users (id) on delete cascade,
  character_id  bigint not null references public.characters (id) on delete cascade,
  equipped_at   timestamptz not null default now()
);

create index if not exists equipped_avatar_character_id_idx on public.equipped_avatar (character_id);

-- ============ audit log ============
create table if not exists public.audit_log (
  id          bigint generated by default as identity primary key,
  user_id     bigint references public.users (id) on delete set null,
  username    text,
  event       text not null,
  detail      text,
  ip          text,
  created_at  timestamptz not null default now()
);

create index if not exists audit_log_created_at_idx on public.audit_log (created_at desc);
create index if not exists audit_log_user_id_idx on public.audit_log (user_id);
create index if not exists audit_log_event_idx on public.audit_log (event);

-- ============ login security functions ============
-- Each one is a single atomic statement, so two logins at the same moment cannot
-- cause a wrong attempt count.

-- Adds one failed attempt. After p_max_attempts failures the account is locked for
-- p_lock_minutes. Returns the lock expiry if the account is locked now, otherwise NULL.
create or replace function public.record_failed_login(
  p_user_id bigint, p_max_attempts integer, p_lock_minutes integer
) returns timestamptz
language plpgsql set search_path = public as $$
declare
  v_locked timestamptz;
begin
  update public.users set
    failed_login_attempts = case when failed_login_attempts + 1 >= p_max_attempts
                                 then 0 else failed_login_attempts + 1 end,
    locked_until = case when failed_login_attempts + 1 >= p_max_attempts
                        then now() + make_interval(mins => p_lock_minutes) else locked_until end
  where id = p_user_id
  returning locked_until into v_locked;

  if v_locked is not null and v_locked > now() then
    return v_locked;
  end if;
  return null;
end;
$$;

create or replace function public.record_successful_login(p_user_id bigint)
returns void
language sql set search_path = public as $$
  update public.users
     set failed_login_attempts = 0, locked_until = null, last_login_at = now()
   where id = p_user_id;
$$;

-- Sets a new password hash and invalidates every existing login token. Returns the new token_version.
create or replace function public.change_password(p_user_id bigint, p_hash text)
returns integer
language plpgsql set search_path = public as $$
declare
  v_version integer;
begin
  update public.users
     set password_hash = p_hash, token_version = token_version + 1,
         failed_login_attempts = 0, locked_until = null
   where id = p_user_id
  returning token_version into v_version;
  return v_version;
end;
$$;

-- Logs the user out everywhere by invalidating every login token. Returns the new token_version.
create or replace function public.revoke_tokens(p_user_id bigint)
returns integer
language plpgsql set search_path = public as $$
declare
  v_version integer;
begin
  update public.users set token_version = token_version + 1
   where id = p_user_id
  returning token_version into v_version;
  return v_version;
end;
$$;

-- Progress is kept PER CHARACTER: every character a player uses has its own XP, level, wins and Prestige.
-- equipped_avatar only says which character is currently equipped.
create table if not exists public.avatar_progress (
  user_id       bigint not null references public.users (id) on delete cascade,
  character_id  bigint not null references public.characters (id) on delete cascade,
  xp            integer not null default 0 check (xp >= 0),            -- XP since this character's last Prestige
  level         integer not null default 1 check (level between 1 and 100),
  prestige      smallint not null default 0 check (prestige between 0 and 100),
  wins          integer not null default 0 check (wins >= 0),
  updated_at    timestamptz not null default now(),
  primary key (user_id, character_id)
);
alter table public.avatar_progress enable row level security;

-- One row per Prestige earned by a character (the Prestige history).
create table if not exists public.prestige_history (
  id               bigint generated by default as identity primary key,
  user_id          bigint not null references public.users (id) on delete cascade,
  character_id     bigint not null references public.characters (id) on delete cascade,
  prestige         smallint not null check (prestige between 1 and 100),
  wins_at_prestige integer not null default 0,
  achieved_at      timestamptz not null default now(),
  constraint prestige_history_key unique (user_id, character_id, prestige)
);
alter table public.prestige_history enable row level security;

-- ============ avatar functions ============
-- Leveling rules (every number is passed in by the API, so balancing never needs SQL changes):
--   Level L -> L+1 needs p_base + p_step * L XP (defaults 500 + 20 x level). Levels are 1..p_max_level.
--   xp is the XP earned by that character since its last Prestige; the level is worked out from it.
--   Excess XP carries over, and one big reward can give several levels at once.
drop function if exists public.avatar_level_for_xp(integer);
drop function if exists public.add_avatar_xp(bigint, integer, integer);

create or replace function public.avatar_level_for_xp(p_xp integer, p_base integer, p_step integer, p_max_level integer)
returns integer
language plpgsql immutable set search_path = public as $$
declare
  v_level integer := 1;
  v_left  bigint  := greatest(p_xp, 0);
begin
  while v_level < p_max_level and v_left >= p_base + p_step * v_level loop
    v_left  := v_left - (p_base + p_step * v_level);
    v_level := v_level + 1;
  end loop;
  return v_level;
end;
$$;

-- Equips a character (replaces the current one, never a second row) and makes sure it has a progress row.
-- Nothing is ever reset: switching characters just switches which character's progress is shown.
create or replace function public.equip_avatar(p_user_id bigint, p_character_id bigint)
returns jsonb
language plpgsql set search_path = public as $$
declare
  v_row public.equipped_avatar;
begin
  insert into public.avatar_progress (user_id, character_id)
  values (p_user_id, p_character_id)
  on conflict do nothing;

  insert into public.equipped_avatar (user_id, character_id)
  values (p_user_id, p_character_id)
  on conflict (user_id) do update set
    equipped_at  = case when equipped_avatar.character_id = excluded.character_id
                        then equipped_avatar.equipped_at else now() end,
    character_id = excluded.character_id
  returning * into v_row;

  return to_jsonb(v_row);
end;
$$;

-- Awards the XP for one finished game to the EQUIPPED character and counts one win.
-- Total XP = p_base_xp + that character's prestige * p_prestige_xp (read from the database, never from the client).
-- Rows are locked first, so two wins arriving together cannot overwrite each other.
-- p_cooldown_seconds blocks wins that arrive too fast (per player, so switching characters does not bypass it).
-- XP stops growing once the character is at max level (it waits for the player to Prestige).
-- Returns {"status": "xp_gained" | "no_avatar" | "cooldown", "old_level": n, "xp_gained": n, "prestige_bonus": n}
create or replace function public.add_avatar_xp(
  p_user_id bigint, p_base_xp integer, p_cooldown_seconds integer,
  p_level_base integer, p_level_step integer, p_max_level integer, p_prestige_xp integer)
returns jsonb
language plpgsql set search_path = public as $$
declare
  v_char     bigint;
  v_prog     public.avatar_progress;
  v_last_win timestamptz;
  v_bonus    integer;
  v_cap      integer;
  v_new_xp   integer;
begin
  if p_base_xp is null or p_base_xp < 0 or p_prestige_xp is null or p_prestige_xp < 0 then
    raise exception 'XP values must not be negative';
  end if;

  select character_id into v_char from public.equipped_avatar where user_id = p_user_id for update;
  if not found then
    return jsonb_build_object('status', 'no_avatar');
  end if;

  insert into public.avatar_progress (user_id, character_id) values (p_user_id, v_char) on conflict do nothing;
  select * into v_prog from public.avatar_progress where user_id = p_user_id and character_id = v_char for update;
  select last_win_at into v_last_win from public.users where id = p_user_id for update;
  v_bonus := v_prog.prestige * p_prestige_xp;

  if v_last_win is not null and v_last_win > now() - make_interval(secs => p_cooldown_seconds) then
    return jsonb_build_object('status', 'cooldown', 'old_level', v_prog.level, 'xp_gained', 0, 'prestige_bonus', v_bonus);
  end if;

  -- total XP needed to be at max level: sum of (base + step * L) for L = 1 .. max-1
  v_cap    := p_level_base * (p_max_level - 1) + p_level_step * (p_max_level - 1) * p_max_level / 2;
  v_new_xp := least(v_prog.xp::bigint + p_base_xp + v_bonus, v_cap);

  update public.avatar_progress
     set xp = v_new_xp,
         wins = wins + 1,
         updated_at = now(),
         level = public.avatar_level_for_xp(v_new_xp, p_level_base, p_level_step, p_max_level)
   where user_id = p_user_id and character_id = v_char;
  update public.users set last_win_at = now() where id = p_user_id;

  return jsonb_build_object('status', 'xp_gained', 'old_level', v_prog.level,
                            'xp_gained', v_new_xp - v_prog.xp, 'prestige_bonus', v_bonus);
end;
$$;

-- Prestige for the EQUIPPED character: only at max level and below max prestige. Resets that character to
-- level 1 / 0 XP, adds 1 to its prestige and writes a prestige_history row. Wins are kept.
-- Returns {"status": "prestiged" | "no_avatar" | "not_max_level" | "max_prestige", "prestige": n}
create or replace function public.prestige_avatar(p_user_id bigint, p_max_level integer, p_max_prestige integer)
returns jsonb
language plpgsql set search_path = public as $$
declare
  v_char bigint;
  v_prog public.avatar_progress;
begin
  select character_id into v_char from public.equipped_avatar where user_id = p_user_id for update;
  if not found then
    return jsonb_build_object('status', 'no_avatar');
  end if;
  insert into public.avatar_progress (user_id, character_id) values (p_user_id, v_char) on conflict do nothing;
  select * into v_prog from public.avatar_progress where user_id = p_user_id and character_id = v_char for update;

  if v_prog.level < p_max_level then
    return jsonb_build_object('status', 'not_max_level', 'prestige', v_prog.prestige);
  end if;
  if v_prog.prestige >= p_max_prestige then
    return jsonb_build_object('status', 'max_prestige', 'prestige', v_prog.prestige);
  end if;

  update public.avatar_progress
     set xp = 0, level = 1, prestige = prestige + 1, updated_at = now()
   where user_id = p_user_id and character_id = v_char;
  insert into public.prestige_history (user_id, character_id, prestige, wins_at_prestige)
  values (p_user_id, v_char, v_prog.prestige + 1, v_prog.wins);

  return jsonb_build_object('status', 'prestiged', 'prestige', v_prog.prestige + 1);
end;
$$;

-- ============ lock everything down ============
-- 1) Row-level security ON with no policies: the public publishable key can read or write nothing.
alter table public.roles            enable row level security;
alter table public.users            enable row level security;
alter table public.equipped_avatar  enable row level security;
