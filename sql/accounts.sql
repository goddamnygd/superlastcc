-- Accounts: roles, users, equipped avatar, audit log and the security functions.
-- Run in the Supabase SQL Editor AFTER schema.sql and seed.sql.
-- If you had an older version of these tables, run reset_accounts.sql first.
--
-- How the tables connect:
--   roles 1 ---- * users             users.role_id -> roles.id
--   users 1 ---- 0..1 characters     through equipped_avatar (user_id is the primary key,
--                                    so one user can only ever equip ONE avatar)
--   users 1 ---- * audit_log         audit_log.user_id -> users.id (kept as NULL if the user is deleted)

-- ============ roles ============
create table if not exists public.roles (
  id           smallint primary key,
  name         text not null unique check (name = lower(name)),
  description  text not null
);

-- Fixed ids: the API relies on 1 = user and 2 = admin
insert into public.roles (id, name, description) values
  (1, 'user',  'Normal account. Manages own profile, equips one avatar and levels it up by winning games.'),
  (2, 'admin', 'Can manage characters and other accounts, and read the audit log.')
on conflict (id) do nothing;

-- ============ users ============
create table if not exists public.users (
  id                     bigint generated by default as identity primary key,
  username               text not null,
  email                  text not null,
  password_hash          text not null,
  role_id                smallint not null default 1
                           references public.roles (id) on update cascade on delete restrict,
  is_active              boolean not null default true,
  token_version          integer not null default 0,   -- raising this invalidates every login token
  failed_login_attempts  integer not null default 0 check (failed_login_attempts >= 0),
  locked_until           timestamptz,
  last_login_at          timestamptz,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  constraint users_username_key unique (username),
  constraint users_email_key unique (email),
  constraint users_username_format check (username ~ '^[a-z0-9_]{3,30}$'),
  constraint users_email_lowercase check (email = lower(email))
);

create index if not exists users_role_id_idx on public.users (role_id);

-- Keep updated_at fresh on every update (also created in schema.sql, safe to repeat)
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists users_set_updated_at on public.users;
create trigger users_set_updated_at
before update on public.users
for each row execute function public.set_updated_at();

-- The system must always keep at least one active admin. This is enforced here, in the
-- database, so no API bug or race can lock everyone out. (role id 2 = admin)
create or replace function public.protect_last_admin()
returns trigger language plpgsql set search_path = public as $$
begin
  if old.role_id = 2 and old.is_active then
    if tg_op = 'DELETE' or new.role_id <> 2 or not new.is_active then
      if not exists (
        select 1 from public.users where role_id = 2 and is_active and id <> old.id
      ) then
        raise exception 'last_admin: at least one active admin must remain' using errcode = 'P0001';
      end if;
    end if;
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists users_protect_last_admin on public.users;
create trigger users_protect_last_admin
before update or delete on public.users
for each row execute function public.protect_last_admin();

-- ============ equipped avatar ============
-- user_id is the PRIMARY KEY, so the database itself guarantees one avatar per user.
-- xp, level and wins belong to the equipped avatar. Switching to a different character resets them.
-- level is worked out from xp by avatar_level_for_xp() (see the leveling rules below).
create table if not exists public.equipped_avatar (
  user_id       bigint primary key references public.users (id) on delete cascade,
  character_id  bigint not null references public.characters (id) on delete cascade,
  xp            integer not null default 0 check (xp >= 0),
  level         integer not null default 0 check (level >= 0),
  wins          integer not null default 0 check (wins >= 0),
  equipped_at   timestamptz not null default now(),
  last_win_at   timestamptz
);

create index if not exists equipped_avatar_character_id_idx on public.equipped_avatar (character_id);

-- ============ audit log ============
create table if not exists public.audit_log (
  id          bigint generated by default as identity primary key,
  user_id     bigint references public.users (id) on delete set null,
  username    text,
  event       text not null,
  detail      text,
  ip          text,
  created_at  timestamptz not null default now()
);

create index if not exists audit_log_created_at_idx on public.audit_log (created_at desc);
create index if not exists audit_log_user_id_idx on public.audit_log (user_id);
create index if not exists audit_log_event_idx on public.audit_log (event);

-- ============ login security functions ============
-- Each one is a single atomic statement, so two logins at the same moment cannot
-- cause a wrong attempt count.

-- Adds one failed attempt. After p_max_attempts failures the account is locked for
-- p_lock_minutes. Returns the lock expiry if the account is locked now, otherwise NULL.
create or replace function public.record_failed_login(
  p_user_id bigint, p_max_attempts integer, p_lock_minutes integer
) returns timestamptz
language plpgsql set search_path = public as $$
declare
  v_locked timestamptz;
begin
  update public.users set
    failed_login_attempts = case when failed_login_attempts + 1 >= p_max_attempts
                                 then 0 else failed_login_attempts + 1 end,
    locked_until = case when failed_login_attempts + 1 >= p_max_attempts
                        then now() + make_interval(mins => p_lock_minutes) else locked_until end
  where id = p_user_id
  returning locked_until into v_locked;

  if v_locked is not null and v_locked > now() then
    return v_locked;
  end if;
  return null;
end;
$$;

create or replace function public.record_successful_login(p_user_id bigint)
returns void
language sql set search_path = public as $$
  update public.users
     set failed_login_attempts = 0, locked_until = null, last_login_at = now()
   where id = p_user_id;
$$;

-- Sets a new password hash and invalidates every existing login token. Returns the new token_version.
create or replace function public.change_password(p_user_id bigint, p_hash text)
returns integer
language plpgsql set search_path = public as $$
declare
  v_version integer;
begin
  update public.users
     set password_hash = p_hash, token_version = token_version + 1,
         failed_login_attempts = 0, locked_until = null
   where id = p_user_id
  returning token_version into v_version;
  return v_version;
end;
$$;

-- Logs the user out everywhere by invalidating every login token. Returns the new token_version.
create or replace function public.revoke_tokens(p_user_id bigint)
returns integer
language plpgsql set search_path = public as $$
declare
  v_version integer;
begin
  update public.users set token_version = token_version + 1
   where id = p_user_id
  returning token_version into v_version;
  return v_version;
end;
$$;

-- ============ avatar functions ============
-- Leveling rules: every win gives XP (the API sends 50).
--   Level 1 needs 100 XP, and each next level needs 1.25 times the XP of the level before:
--   100, 125, 156, 195, 244 ... (each amount rounded down). XP carries over, nothing is lost.
create or replace function public.avatar_level_for_xp(p_xp integer)
returns integer
language plpgsql immutable set search_path = public as $$
declare
  v_level integer := 0;
  v_left  numeric := greatest(p_xp, 0);
  v_need  numeric := 100;
begin
  while v_left >= floor(v_need) loop
    v_left  := v_left - floor(v_need);
    v_level := v_level + 1;
    v_need  := v_need * 1.25;
  end loop;
  return v_level;
end;
$$;

-- Equips a character. If the user already has an avatar it is REPLACED (never a second row).
-- Re-equipping the same character keeps its XP and level; a different character starts at 0 XP, level 0.
create or replace function public.equip_avatar(p_user_id bigint, p_character_id bigint)
returns jsonb
language plpgsql set search_path = public as $$
declare
  v_row public.equipped_avatar;
begin
  insert into public.equipped_avatar (user_id, character_id)
  values (p_user_id, p_character_id)
  on conflict (user_id) do update set
    xp          = case when equipped_avatar.character_id = excluded.character_id
                       then equipped_avatar.xp else 0 end,
    level       = case when equipped_avatar.character_id = excluded.character_id
                       then equipped_avatar.level else 0 end,
    wins        = case when equipped_avatar.character_id = excluded.character_id
                       then equipped_avatar.wins else 0 end,
    last_win_at = case when equipped_avatar.character_id = excluded.character_id
                       then equipped_avatar.last_win_at else null end,
    equipped_at = case when equipped_avatar.character_id = excluded.character_id
                       then equipped_avatar.equipped_at else now() end,
    character_id = excluded.character_id
  returning * into v_row;

  return to_jsonb(v_row);
end;
$$;

-- Adds p_xp experience and one win to the equipped avatar, then recalculates the level.
-- The row is locked first, so two wins arriving together cannot overwrite each other.
-- p_cooldown_seconds blocks wins that arrive too fast after the previous one.
-- Returns {"status": "xp_gained" | "no_avatar" | "cooldown", "old_level": n, "avatar": {...}}
create or replace function public.add_avatar_xp(p_user_id bigint, p_xp integer, p_cooldown_seconds integer)
returns jsonb
language plpgsql set search_path = public as $$
declare
  v_row public.equipped_avatar;
  v_old integer;
begin
  if p_xp is null or p_xp < 1 then
    raise exception 'p_xp must be at least 1';
  end if;

  select level into v_old from public.equipped_avatar where user_id = p_user_id for update;
  if not found then
    return jsonb_build_object('status', 'no_avatar');
  end if;

  update public.equipped_avatar
     set xp = xp + p_xp,
         wins = wins + 1,
         last_win_at = now(),
         level = public.avatar_level_for_xp(xp + p_xp)
   where user_id = p_user_id
     and (last_win_at is null or last_win_at <= now() - make_interval(secs => p_cooldown_seconds))
  returning * into v_row;

  if found then
    return jsonb_build_object('status', 'xp_gained', 'old_level', v_old, 'avatar', to_jsonb(v_row));
  end if;

  select * into v_row from public.equipped_avatar where user_id = p_user_id;
  return jsonb_build_object('status', 'cooldown', 'old_level', v_old, 'avatar', to_jsonb(v_row));
end;
$$;

-- ============ lock everything down ============
-- 1) Row-level security ON with no policies: the public publishable key can read or write nothing.
alter table public.roles            enable row level security;
alter table public.users            enable row level security;
alter table public.equipped_avatar  enable row level security;
alter table public.audit_log        enable row level security;

-- 2) Only the API (secret key = service_role) may call the functions or touch the tables.
--    Written as a block so it also runs on a plain Postgres that has no Supabase roles.
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon')
     and exists (select 1 from pg_roles where rolname = 'authenticated')
     and exists (select 1 from pg_roles where rolname = 'service_role') then

    revoke all on public.roles, public.users, public.equipped_avatar, public.audit_log
      from anon, authenticated;

    revoke all on function public.record_failed_login(bigint, integer, integer),
                           public.record_successful_login(bigint),
                           public.change_password(bigint, text),
                           public.revoke_tokens(bigint),
                           public.equip_avatar(bigint, bigint),
                           public.avatar_level_for_xp(integer),
                           public.add_avatar_xp(bigint, integer, integer)
      from public, anon, authenticated;

    grant execute on function public.record_failed_login(bigint, integer, integer),
                              public.record_successful_login(bigint),
                              public.change_password(bigint, text),
                              public.revoke_tokens(bigint),
                              public.equip_avatar(bigint, bigint),
                              public.avatar_level_for_xp(integer),
                              public.add_avatar_xp(bigint, integer, integer)
      to service_role;
  end if;
end
$$;

