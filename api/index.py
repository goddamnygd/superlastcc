_dummy_hash_value: Optional[bytes] = None


def hash_password(password: str) -> str:
    return bcrypt.hashpw(password.encode(), bcrypt.gensalt()).decode()


def check_password(password: str, hashed: str) -> bool:
    try:
        return bcrypt.checkpw(password.encode(), hashed.encode())
    except ValueError:
        return False


def burn_password_check(password: str):
    """Unknown username: still spend the same time hashing, so response time does not
    reveal whether an account exists."""
    global _dummy_hash_value
    if _dummy_hash_value is None:
        _dummy_hash_value = bcrypt.hashpw(b"not-a-real-password", bcrypt.gensalt())
    bcrypt.checkpw(password.encode()[:72], _dummy_hash_value)


def make_token(user: dict) -> str:
    if not JWT_SECRET:
        logger.error("JWT_SECRET is not set.")
        raise NotConfigured()
    now = datetime.now(timezone.utc)
    payload = {
        "sub": str(user["id"]),
        "ver": user["token_version"],   # must match users.token_version, so it can be revoked
        "iat": now,
        "exp": now + timedelta(hours=TOKEN_HOURS),
    }
    return jwt.encode(payload, JWT_SECRET, algorithm="HS256")


def user_from_authorization(authorization: Optional[str]) -> dict:
    """Turns an 'Authorization: Bearer <token>' header into a user row, or raises 401."""
    if not authorization or not authorization.lower().startswith("bearer "):
        raise HTTPException(status_code=401, detail="Login required.", headers={"WWW-Authenticate": "Bearer"})
    if not JWT_SECRET:
        logger.error("JWT_SECRET is not set.")
        raise NotConfigured()
    try:
        payload = jwt.decode(
            authorization[7:].strip(), JWT_SECRET, algorithms=["HS256"],
            options={"require": ["exp", "sub", "ver"]},
        )
        user_id, version = int(payload["sub"]), int(payload["ver"])
    except (jwt.PyJWTError, ValueError, KeyError, TypeError):
        raise HTTPException(status_code=401, detail="Invalid or expired token.")
    # Checked against the database on every request, so disabling an account or
    # changing a role takes effect immediately.
    user = db_user_by_id(user_id)
    if user is None or not user["is_active"] or user["token_version"] != version:
        raise HTTPException(status_code=401, detail="Invalid or expired token.")
    return user


def get_current_user(authorization: Optional[str] = Header(default=None)) -> dict:
    return user_from_authorization(authorization)


def require_admin(user: dict = Depends(get_current_user)) -> dict:
    if user["role_id"] != ADMIN_ROLE_ID:
        raise HTTPException(status_code=403, detail="Admin access required.")
    return user


def client_ip(request: Request) -> Optional[str]:
    forwarded = request.headers.get("x-forwarded-for", "").split(",")[0].strip()
    return forwarded or (request.client.host if request.client else None)


def is_locked(locked_until) -> bool:
    if not locked_until:
        return False
    try:
        when = datetime.fromisoformat(str(locked_until).replace("Z", "+00:00"))
    except ValueError:
        return True  # cannot read the value, so stay safe
    if when.tzinfo is None:
        when = when.replace(tzinfo=timezone.utc)
    return when > datetime.now(timezone.utc)


