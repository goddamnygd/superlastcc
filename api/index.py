@app.post("/api/v1/auth/login")
def login(body: LoginBody, request: Request):
    ip = client_ip(request)
    identifier = body.identifier.strip().lower()
    user = db_user_by_login(identifier)

    if user is None:
        burn_password_check(body.password)
        db_audit("login_failed", detail="unknown account", ip=ip)
        raise HTTPException(status_code=401, detail="Wrong username/email or password.")

    if is_locked(user["locked_until"]):
        db_audit("login_blocked", user["id"], user["username"], "account locked", ip)
        raise HTTPException(status_code=423, detail="Too many failed attempts. Try again in a few minutes.")

    if not check_password(body.password, user["password_hash"]):
        locked = db_rpc("record_failed_login", {
            "p_user_id": user["id"],
            "p_max_attempts": MAX_LOGIN_ATTEMPTS,
            "p_lock_minutes": LOCK_MINUTES,
        })
        db_audit("login_failed", user["id"], user["username"], "wrong password", ip)
        if locked:
            raise HTTPException(status_code=423, detail="Too many failed attempts. Try again in a few minutes.")
        raise HTTPException(status_code=401, detail="Wrong username/email or password.")

    # Only said after the password is right, so it does not reveal which accounts exist
    if not user["is_active"]:
        db_audit("login_blocked", user["id"], user["username"], "account disabled", ip)
        raise HTTPException(status_code=403, detail="This account has been disabled.")

    db_rpc("record_successful_login", {"p_user_id": user["id"]})
    db_audit("login", user["id"], user["username"], ip=ip)
    return {"token": make_token(user), "user": public_user(user)}


@app.post("/api/v1/auth/change-password")
def change_password(body: ChangePasswordBody, request: Request, user: dict = Depends(get_current_user)):
    full = db_user_by_id(user["id"], with_hash=True)
    if not check_password(body.current_password, full["password_hash"]):
        db_audit("password_change_failed", user["id"], user["username"], ip=client_ip(request))
        raise HTTPException(status_code=400, detail="Current password is wrong.")
    new_version = db_rpc("change_password", {"p_user_id": user["id"], "p_hash": hash_password(body.new_password)})
    db_audit("password_changed", user["id"], user["username"], ip=client_ip(request))
    # Every old token is dead now, so hand back a fresh one for this device
    return {"message": "Password changed.", "token": make_token({**user, "token_version": new_version})}


