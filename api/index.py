def xp_for_next_level(level: int) -> int:
    return LEVEL_BASE_XP + LEVEL_STEP_XP * level


def level_progress(xp: int) -> dict:
    """Where an avatar stands for a given XP total. Mirrors avatar_level_for_xp() in the database."""
    level, left = 1, max(int(xp), 0)
    while level < MAX_LEVEL and left >= xp_for_next_level(level):
        left -= xp_for_next_level(level)
        level += 1
    at_max = level >= MAX_LEVEL
    return {
        "level": level,
        "xp_into_level": 0 if at_max else left,
        "xp_for_next_level": 0 if at_max else xp_for_next_level(level),
        "max_level": MAX_LEVEL,
        "level_progress_percent": 100.0 if at_max else round((level - 1) / (MAX_LEVEL - 1) * 100, 1),
    }


def with_progress(avatar: Optional[dict]) -> Optional[dict]:
    """Adds the progress bar numbers to an avatar row."""
    if not avatar:
        return avatar
    progress = level_progress(avatar["xp"])
    progress.pop("level")   # the stored level is the source of truth
    prestige = avatar.get("prestige", 0)
    return {**avatar, **progress,
            "prestige_bonus_xp": prestige * PRESTIGE_XP_PER_LEVEL,
            "can_prestige": avatar["level"] >= MAX_LEVEL and prestige < MAX_PRESTIGE}


def db_get_avatar(user_id: int):
    """The equipped character together with ITS OWN xp / level / prestige / wins (avatar_progress)."""
    res = run(get_client().table("equipped_avatar").select(AVATAR_COLUMNS).eq("user_id", user_id).limit(1))
    if not res.data:
        return None
    avatar = res.data[0]
    prog = run(
        get_client().table("avatar_progress").select("xp, level, prestige, wins")
        .eq("user_id", user_id).eq("character_id", avatar["character_id"]).limit(1)
    ).data
    prog = prog[0] if prog else {"xp": 0, "level": 1, "prestige": 0, "wins": 0}
    return with_progress({**avatar, **prog})


def db_audit(event: str, user_id: Optional[int] = None, username: Optional[str] = None,
             detail: Optional[str] = None, ip: Optional[str] = None):
    """Writing the audit log must never break the request it belongs to."""
    try:
        get_client().table("audit_log").insert(
            {"event": event, "user_id": user_id, "username": username, "detail": detail, "ip": ip}
        ).execute()
    except Exception:
        logger.exception("Could not write audit log entry '%s'.", event)


def db_list_audit(limit: int, offset: int, event: Optional[str]):
    q = get_client().table("audit_log").select("*", count="exact")
    if event:
        q = q.eq("event", event)
    res = run(q.order("created_at", desc=True).order("id", desc=True).range(offset, offset + limit - 1))
    return res.data, res.count or 0


