def _matches(sent: Optional[str], expected: Optional[str]) -> bool:
    if not sent or not expected:
        return False
    return secrets.compare_digest(sent.encode(), expected.encode())


def verify_api_key(x_api_key: Optional[str] = Header(default=None)):
    """Read access. Used by the web apps."""
    if not _matches(x_api_key, API_KEY):
        raise HTTPException(status_code=401, detail="Invalid or missing API key.")
    return True


def verify_admin_key(
    x_admin_key: Optional[str] = Header(default=None),
    authorization: Optional[str] = Header(default=None),
):
    """Write access (create, update, delete characters).
    Allowed with the admin API key OR with the login token of a user whose role is admin."""
    if _matches(x_admin_key, ADMIN_API_KEY):
        return True
    if authorization:
        user = user_from_authorization(authorization)
        if user["role_id"] == ADMIN_ROLE_ID:
            return True
        raise HTTPException(status_code=403, detail="Admin access required.")
    raise HTTPException(status_code=401, detail="Invalid or missing admin credentials.")


